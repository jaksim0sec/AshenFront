"""Measure opaque silhouette hulls; never modify source PNGs."""
import json
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
def cross(o,a,b):return (a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0])
def hull(points):
 points=sorted(set(points));low=[];high=[]
 for p in points:
  while len(low)>=2 and cross(low[-2],low[-1],p)<=0:low.pop()
  low.append(p)
 for p in reversed(points):
  while len(high)>=2 and cross(high[-2],high[-1],p)<=0:high.pop()
  high.append(p)
 return low[:-1]+high[:-1]
result={}
for key,meta in json.loads((root/'assets/soldiers/manifest.json').read_text())['assets'].items():
 im=Image.open(root/meta['path']).convert('RGBA');x0,y0,x1,y1=meta['crop'];alpha=im.getchannel('A').crop((x0,y0,x1,y1));w,h=alpha.size;data=list(alpha.tobytes());points=[]
 for y in range(h):
  xs=[x for x in range(w) if data[y*w+x]>=128]
  if xs:points.extend([(xs[0],y),(xs[-1]+1,y),(xs[0],y+1),(xs[-1]+1,y+1)])
 result[key]=[[x/w,y/h] for x,y in hull(points)]
(root/'src/characters/contact-hulls.mjs').write_text('// Alpha>=128 pixel silhouette hulls. Generated by tools/soldier-contact-hulls.py.\nexport const CONTACT_HULLS='+json.dumps(result,separators=(',',':'))+';\n')
