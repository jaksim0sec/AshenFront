#!/usr/bin/env python3
"""Import the supplied calibrated uniform archive without changing PNG pixels."""
import hashlib
import json
import math
from pathlib import Path
import struct
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'assets/soldiers'
# Match the existing game's sprite size and foot origin with one global transform.
UNIT = 100 / 312
ORIGIN = (320, 732.6)
PALMS = {
    'black/arm_left': (47.46, 166.94),
    'black/arm_right': (119.73, 167.20),
    'blue/arm_left': (57.11, 182.13),
    'blue/arm_right': (128.22, 181.43),
}


def main(archive):
    archive = Path(archive)
    manifest = {
        'format': 'ashenfront-soldier-assets', 'version': 1,
        'sourceArchive': archive.name,
        'archiveSha256': hashlib.sha256(archive.read_bytes()).hexdigest(),
        'note': 'Unchanged native PNG crops. Full-crop rendering preserves padding and aspect ratio. '
                'Assembly coordinates, uniform scales and layers come from this archive rig.json. '
                'Arken uses black; Velian uses blue.',
        'assemblyToGame': {'scale': UNIT, 'originPx': ORIGIN},
        'assets': {},
    }
    parts, aspects, images = {}, {'rifle-placeholder': 4}, {}
    with zipfile.ZipFile(archive) as z:
        rig_bytes = z.read('rig.json')
        rig = json.loads(rig_bytes)
        for key, p in rig['parts'].items():
            file = p['file']
            if file != key + '.png' or len(Path(file).parts) != 2 or '..' in Path(file).parts:
                raise ValueError('Invalid asset path: ' + file)
            data = z.read(file)
            digest = hashlib.sha256(data).hexdigest()
            if digest != p['png_sha256'] or data[:8] != b'\x89PNG\r\n\x1a\n':
                raise ValueError('PNG checksum mismatch: ' + file)
            w, h = struct.unpack('>II', data[16:24])
            if [w, h] != p['size_px']:
                raise ValueError('PNG size mismatch: ' + file)
            sx, sy = p['scale_correction']
            if not math.isclose(sx, sy, abs_tol=1e-12):
                raise ValueError('Nonuniform source scale: ' + key)
            a = p['assembly']
            x, y = a['position_px']
            px, py = p['pivot_px']
            parts[key] = {
                'asset': key, 'x': (x - ORIGIN[0]) * UNIT, 'y': (y - ORIGIN[1]) * UNIT,
                'w': w * sx * UNIT, 'h': h * sx * UNIT,
                'pivotX': px / w, 'pivotY': py / h,
                'rotation': math.radians(a['rotation_deg']),
                'scaleX': 1, 'scaleY': 1, 'visible': True,
            }
            if key in PALMS:
                parts[key].update(gripX=PALMS[key][0] / w, gripY=PALMS[key][1] / h)
            aspects[key] = w / h
            images[file] = data
            manifest['assets'][key] = {
                'path': 'assets/soldiers/' + file, 'width': w, 'height': h,
                'crop': [0, 0, w, h], 'visibleBounds': p['visible_bounds_px'], 'sha256': digest,
            }
        assemblies = {}
        for name, a in rig['assemblies'].items():
            for key, node in a['nodes'].items():
                expected = rig['parts'][key]['assembly']['matrix_2x3']
                if any(abs(x - y) > 1e-7 for row, target in zip(node['canvas_matrix_2x3'], expected)
                       for x, y in zip(row, target)):
                    raise ValueError('Preset overrides need explicit support: ' + name)
            assemblies[name] = sorted(a['nodes'], key=lambda key: a['nodes'][key]['z_index'])
    # Validate the entire archive before replacing any published files.
    old = json.loads((DEST / 'manifest.json').read_text())
    for data in old['assets'].values():
        path = ROOT / data['path']
        if path.is_relative_to(DEST) and path.suffix == '.png' and str(path.relative_to(DEST)) not in images:
            path.unlink(missing_ok=True)
    for file, data in images.items():
        path = DEST / file
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    (DEST / 'rig.json').write_bytes(rig_bytes)
    (DEST / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (ROOT / 'src/characters/aspects.mjs').write_text(
        '// Native crop aspect ratios; generated by tools/import-uniform-parts.py.\n'
        'export const ASPECTS=Object.freeze(' + json.dumps(aspects, indent=2) + ');\n')
    (ROOT / 'src/characters/uniforms.mjs').write_text(
        '// Generated from uniform-parts-crops-1.zip rig.json. No raster resizing.\n'
        '// One canvas-to-game scale and foot translation; source pivots/scales/rotations preserved.\n'
        'export const BODY_STYLE="uniform-parts-crops-1";\n'
        'export const UNIFORM_PARTS=' + json.dumps(parts, separators=(',', ':')) + ';\n'
        'export const ASSEMBLIES=' + json.dumps(assemblies, separators=(',', ':')) + ';\n')
    print(f'Imported {len(images)} unchanged PNGs and {len(assemblies)} calibrated assemblies.')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('Usage: python3 tools/import-uniform-parts.py uniform-parts-crops-1.zip')
    main(sys.argv[1])
